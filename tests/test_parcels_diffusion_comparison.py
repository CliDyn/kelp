"""Cross-comparison @slow tests: kelp vs Parcels v4 on diffusion benchmarks.

This is the Option-B follow-up to ``tests/test_parcels_diffusion_parity.py``
(which is native-only).  Here we run kelp on the *same physical
setup* as Parcels' two diffusion benchmarks and compare distribution
moments.

The two systems use *different* RNG streams (Parcels: ``np.random`` with
seed; kelp: counter-RNG with seed) so per-particle agreement is
impossible.  At the npart used in the reference runs (10 000 for
Brownian, 50 000 for spatially-varying), the *moments* (mean, std,
skewness) should converge to the same values up to statistical noise.

Reference data lives in ``../Parcels/benchmarks_lagdrift/outputs/``
and is generated by:

    cd ../Parcels
    .venv-parcels/bin/python benchmarks_lagdrift/test04_diffusion_brownian.py
    .venv-parcels/bin/python benchmarks_lagdrift/test05_diffusion_spatially_varying.py

If the JSON files are missing (clean checkout / CI without Parcels)
the tests skip with a helpful message — same pattern as
``tests/test_parcels_comparison.py``.

Marked ``@pytest.mark.slow`` so it doesn't run by default.

Run explicitly:
    pytest tests/test_parcels_diffusion_comparison.py -m slow -v -s
"""
from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np
import pytest
from scipy import stats

from kelp.core.geometry import METERS_PER_DEG_LAT
from kelp.core.mesh import Mesh, build_node_to_elems, build_search
from kelp.core.particles import make_state
from kelp.numerics.diffusion import DiffusionStepArgs
from kelp.numerics.integrators import euler_step
from kelp.numerics.interpolate import VelocityField


pytestmark = pytest.mark.slow

PARCELS_DIR = (
    Path(__file__).resolve().parents[2]
    / "Parcels" / "benchmarks_lagdrift" / "outputs"  # kept on purpose: a real name on disk / in the sibling clone, NOT renamed with the package
)


# ---------------------------------------------------------------------------
# Helpers — synthetic mesh, equivalent in scale to Parcels' 2x2 / 200x100
# structured fields but on kelp's unstructured triangular grid.
# ---------------------------------------------------------------------------

def _build_grid_mesh(xs: np.ndarray, ys: np.ndarray) -> Mesh:
    gx, gy = np.meshgrid(xs, ys)
    lon = gx.ravel().astype(np.float64)
    lat = gy.ravel().astype(np.float64)
    nx, ny = len(xs), len(ys)
    n_nodes = nx * ny
    elems = []
    for j in range(ny - 1):
        for i in range(nx - 1):
            n0 = j * nx + i
            n1 = n0 + 1
            n2 = n0 + nx
            n3 = n2 + 1
            elems.append([n0, n1, n2])
            elems.append([n1, n3, n2])
    elem_nodes = np.array(elems, dtype=np.int32)
    lon_c = np.array([lon[e].mean() for e in elem_nodes], dtype=np.float64)
    lat_c = np.array([lat[e].mean() for e in elem_nodes], dtype=np.float64)
    n2e, n2e_count = build_node_to_elems(n_nodes, elem_nodes)
    mesh = Mesh(
        name="grid",
        nodes_lon=lon, nodes_lat=lat, depth=np.zeros(n_nodes),
        elem_nodes=elem_nodes,
        elem_center_lon=lon_c, elem_center_lat=lat_c,
        node_to_elems=n2e, node_to_elems_count=n2e_count,
    )
    build_search(mesh)
    return mesh


# Seed location for the kelp mesh.  Parcels uses (0°, 0°); we seed at
# (10°, 0°) on a mesh spanning [0, 20°] in lon.  Historically this dodged a
# ``build_grid_hash`` nearest-node bug on meshes crossing lon=0 (fixed since:
# branch-picking lon normalization, see TestGridHashLonBranch in
# tests/test_mesh.py).  Kept as-is — the diffusion physics is
# translation-invariant in lon, so the moments are unchanged and the
# validated reference comparison stays untouched.
_SEED_LON = 10.0
_SEED_LAT = 0.0


def _seed_at_origin(n: int):
    """Seed all particles at the workaround point ``(10°, 0°)``."""
    return make_state(
        lon=np.full(n, _SEED_LON, dtype=np.float64),
        lat=np.full(n, _SEED_LAT, dtype=np.float64),
    )


def _print_table(title: str, rows: list[tuple]):
    """Print a side-by-side moment comparison table."""
    print(f"\n  {title}")
    print(f"  {'─' * 72}")
    print(f"  {'metric':<14}{'Parcels v4':>16}{'kelp':>16}{'diff':>16}{'ok?':>8}")
    print(f"  {'─' * 72}")
    for metric, p_val, l_val, tol, ok in rows:
        diff = l_val - p_val
        print(f"  {metric:<14}{p_val:>+16.4f}{l_val:>+16.4f}"
              f"{diff:>+16.4f}{('✓' if ok else '✗'):>8}")
    print(f"  {'─' * 72}")


# ---------------------------------------------------------------------------
# Test 1 — Brownian (uniform Kh)
# ---------------------------------------------------------------------------

class TestParcelsBrownianComparison:
    """Compare kelp vs Parcels on the uniform-Kh Brownian benchmark.

    Parcels reference: 10 000 particles, kh_zonal=100, kh_meridional=50,
    runtime=2h, dt=1h.  We run kelp with matching parameters and
    cross-check the four moments (means, stds in metres around the
    seed).  At n=10 000 the standard errors are
        SE(mean) ≈ √(2 Kh t / n)  ≈ 12 m  (zonal)  /  8 m (meridional)
        SE(std)  ≈ Kh / √(n) · √(2 t)  ≈ 8.5 m / 6.0 m
    Tolerances of 5σ on each give comfortable headroom.
    """

    def test_brownian_moments_agree(self):
        meta_path = PARCELS_DIR / "test04_brownian_v4.json"
        if not meta_path.exists():
            pytest.skip(
                f"Parcels reference not found at {meta_path}.\n"
                "Generate with: "
                ".venv-parcels/bin/python "
                "benchmarks_lagdrift/test04_diffusion_brownian.py"
            )
        with open(meta_path) as f:
            ref = json.load(f)

        npart = ref["n_particles"]
        kh_zonal = ref["kh_zonal"]
        kh_meridional = ref["kh_meridional"]
        runtime_s = ref["runtime_s"]
        dt_s = ref["dt_s"]
        n_steps = int(runtime_s / dt_s)

        # Mesh: wide enough to keep ±3 sigma in-domain.  For
        # std_zonal=1200 m at lat=0 → ±3600 m ≈ 0.032°.  A ±10°
        # square is overkill but cheap to build.
        mesh = _build_grid_mesh(
            np.linspace(0.0, 20.0, 21),
            np.linspace(-10.0, 10.0, 21),
        )
        ne = mesh.n_elements
        nn = mesh.n_nodes
        vel = VelocityField(
            u=np.zeros(ne), v=np.zeros(ne), eta=np.zeros(nn),
        )
        state = _seed_at_origin(npart)
        for step_i in range(n_steps):
            diff = DiffusionStepArgs(
                scheme="uniform", kh_x=kh_zonal, kh_y=kh_meridional,
                seed=1234, real_id=0, step_i=step_i,
            )
            state = euler_step(state, vel, mesh, dt=dt_s, time_dir=1.0,
                               diffusion=diff)

        alive = state.alive_mask
        # Standardised across the suite: require >95 % survival rather
        # than strict equality, so a single boundary loss doesn't
        # falsely break the moments comparison (review #7b
        # normalisation).  At Brownian σ ≈ 1200 m on a ±10° mesh,
        # virtually all particles stay in-domain.
        assert alive.sum() > 0.95 * npart, (
            f"only {alive.sum()}/{npart} alive — boundary loss too high"
        )

        # Parcels' "spherical" mesh and kelp both use
        # METERS_PER_DEG_LAT = 1852*60 = 111120 (nautical-mile
        # convention), so the metric conversion at the equator
        # (cos 0 = 1) matches exactly.
        z0 = float(np.cos(np.deg2rad(_SEED_LAT))) * METERS_PER_DEG_LAT
        dx_m = (state.lon[alive] - _SEED_LON) * z0
        dy_m = (state.lat[alive] - _SEED_LAT) * METERS_PER_DEG_LAT

        moments = {
            "mean_dx_m": float(np.mean(dx_m)),
            "mean_dy_m": float(np.mean(dy_m)),
            "std_dx_m": float(np.std(dx_m)),
            "std_dy_m": float(np.std(dy_m)),
        }
        ref_m = ref["moments"]

        # Tolerances: 5 SE on means, 5 % on stds.  Conservative — at
        # n=10k we'd hit these comfortably for any correct
        # implementation.
        se_mean_x = np.sqrt(2.0 * kh_zonal * runtime_s / npart)
        se_mean_y = np.sqrt(2.0 * kh_meridional * runtime_s / npart)
        rows = [
            ("mean_dx_m", ref_m["mean_dx_m"], moments["mean_dx_m"],
             5.0 * se_mean_x,
             abs(moments["mean_dx_m"] - ref_m["mean_dx_m"]) < 5.0 * se_mean_x),
            ("mean_dy_m", ref_m["mean_dy_m"], moments["mean_dy_m"],
             5.0 * se_mean_y,
             abs(moments["mean_dy_m"] - ref_m["mean_dy_m"]) < 5.0 * se_mean_y),
            ("std_dx_m", ref_m["std_dx_m"], moments["std_dx_m"],
             0.05 * ref_m["std_dx_m"],
             abs(moments["std_dx_m"] / ref_m["std_dx_m"] - 1.0) < 0.05),
            ("std_dy_m", ref_m["std_dy_m"], moments["std_dy_m"],
             0.05 * ref_m["std_dy_m"],
             abs(moments["std_dy_m"] / ref_m["std_dy_m"] - 1.0) < 0.05),
        ]
        _print_table("Parcels vs kelp — Brownian (uniform Kh)", rows)
        for metric, _, _, _, ok in rows:
            assert ok, f"{metric}: kelp moment outside tolerance vs Parcels"


# ---------------------------------------------------------------------------
# Test 2 — Spatially varying Kh (EM + M1)
# ---------------------------------------------------------------------------

class TestParcelsSpatiallyVaryingComparison:
    """Compare kelp vs Parcels on the tanh-Kh benchmark, EM + M1.

    Parcels reference: 50 000 particles, runtime=3h, dt=1h, tanh-profile
    Kh in lon (range [100, 300] m^2/s) constant in lat.  Both schemes
    produce nearly identical moments at this scale (Parcels' M1
    correction is small for this Kh field).

    We compare four moments side-by-side.  Skewness has SE ≈ √(6/n) ≈
    0.011 at n=50k — both Parcels' and kelp's skew values land in
    [-0.05, +0.05] (noise-dominated for this gradient strength), so
    the comparison tolerates skew differences up to ~5 SE.
    """

    def _build_tanh_kh_vel(self, mesh: Mesh) -> VelocityField:
        """Match Parcels' Kh field on our unstructured node-based grid.

        Parcels' field is symmetric around lon=0; we centre ours on the
        seed so the gradient runs through the seed point.  Parcels uses
        ``ds["lon"][x] / ds["lon"][-1] * 10.0`` with lon ∈ [-1e6, 1e6] m
        → argument ∈ [-10, +10] in normalised metric units.  We mirror
        that with a 1e6 m half-range centred on the seed.
        """
        nn = mesh.n_nodes
        lon_centred_m = (mesh.nodes_lon - _SEED_LON) * METERS_PER_DEG_LAT
        lon_max_m = 1e6  # match Parcels' fixture
        kh_zonal = (
            np.tanh(lon_centred_m / lon_max_m * 10.0) * 100.0 + 200.0
        ).astype(np.float64)
        kh_meridional = kh_zonal.copy()  # Parcels uses the same field for both
        ne = mesh.n_elements
        return VelocityField(
            u=np.zeros(ne), v=np.zeros(ne), eta=np.zeros(nn),
            kh_zonal=kh_zonal, kh_meridional=kh_meridional,
            kh_layout="node",
        )

    @pytest.mark.parametrize("scheme", ["em", "m1"])
    def test_spatially_varying_moments_agree(self, scheme):
        meta_path = PARCELS_DIR / f"test05_{scheme}_v4.json"
        if not meta_path.exists():
            pytest.skip(
                f"Parcels reference not found at {meta_path}.\n"
                "Generate with: "
                ".venv-parcels/bin/python "
                "benchmarks_lagdrift/test05_diffusion_spatially_varying.py"
            )
        with open(meta_path) as f:
            ref = json.load(f)

        npart = ref["n_particles"]
        runtime_s = ref["runtime_s"]
        dt_s = ref["dt_s"]
        n_steps = int(runtime_s / dt_s)

        # Mesh: ±10° gives ±1.1 Mm zonally at the equator, well above
        # the typical ±3-sigma spread of ~6 km at runtime=3h.
        mesh = _build_grid_mesh(
            np.linspace(0.0, 20.0, 41),
            np.linspace(-10.0, 10.0, 41),
        )
        vel = self._build_tanh_kh_vel(mesh)
        state = _seed_at_origin(npart)

        for step_i in range(n_steps):
            diff = DiffusionStepArgs(
                scheme=scheme, kh_x=0.0, kh_y=0.0,
                seed=1636, real_id=0, step_i=step_i,
                composition="combined", dres_m=2000.0,
            )
            with warnings.catch_warnings():
                # M1 emits one warning per realization on
                # spatially-varying Kh (separable-Kh limitation).
                warnings.simplefilter("ignore", RuntimeWarning)
                state = euler_step(state, vel, mesh, dt=dt_s, time_dir=1.0,
                                   diffusion=diff)

        alive = state.alive_mask
        # Allow a few % loss on the boundary; with 50 000 particles
        # and ~6 km spread on a ±1.1 Mm mesh, virtually all should
        # survive.
        assert alive.sum() > 0.98 * npart, (
            f"only {alive.sum()}/{npart} alive — tighten Kh or widen mesh"
        )

        z0 = float(np.cos(np.deg2rad(_SEED_LAT))) * METERS_PER_DEG_LAT
        dx_m = (state.lon[alive] - _SEED_LON) * z0
        dy_m = (state.lat[alive] - _SEED_LAT) * METERS_PER_DEG_LAT

        moments = {
            "mean_dx_m": float(np.mean(dx_m)),
            "mean_dy_m": float(np.mean(dy_m)),
            "std_dx_m": float(np.std(dx_m)),
            "std_dy_m": float(np.std(dy_m)),
            "skew_dx": float(stats.skew(dx_m)),
            "skew_dy": float(stats.skew(dy_m)),
        }
        ref_m = ref["moments"]

        # Mean: O(SE_mean) = std / √n ≈ 2000/√50000 ≈ 9 m.  Allow 5σ.
        # Std:   relative tol 5 %.
        # Skew:  SE = √(6/n) ≈ 0.011.  Allow 7σ ≈ 0.077 — observed
        # diff between Parcels and kelp is ~0.027, but the two
        # systems use different RNG streams *and* different mesh
        # discretisations (structured lat/lon vs unstructured
        # triangular), so 5σ headroom is tighter than ideal.  7σ
        # reduces flicker risk on Parcels updates / future RNG
        # changes while still catching gross Itô-correction sign bugs.
        se_mean = max(ref_m["std_dx_m"], ref_m["std_dy_m"]) / np.sqrt(npart)
        se_skew = np.sqrt(6.0 / npart)
        rows = [
            ("mean_dx_m", ref_m["mean_dx_m"], moments["mean_dx_m"], 5 * se_mean,
             abs(moments["mean_dx_m"] - ref_m["mean_dx_m"]) < 5 * se_mean),
            ("mean_dy_m", ref_m["mean_dy_m"], moments["mean_dy_m"], 5 * se_mean,
             abs(moments["mean_dy_m"] - ref_m["mean_dy_m"]) < 5 * se_mean),
            ("std_dx_m", ref_m["std_dx_m"], moments["std_dx_m"],
             0.05 * ref_m["std_dx_m"],
             abs(moments["std_dx_m"] / ref_m["std_dx_m"] - 1.0) < 0.05),
            ("std_dy_m", ref_m["std_dy_m"], moments["std_dy_m"],
             0.05 * ref_m["std_dy_m"],
             abs(moments["std_dy_m"] / ref_m["std_dy_m"] - 1.0) < 0.05),
            ("skew_dx", ref_m["skew_dx"], moments["skew_dx"], 7 * se_skew,
             abs(moments["skew_dx"] - ref_m["skew_dx"]) < 7 * se_skew),
            ("skew_dy", ref_m["skew_dy"], moments["skew_dy"], 7 * se_skew,
             abs(moments["skew_dy"] - ref_m["skew_dy"]) < 7 * se_skew),
        ]
        _print_table(
            f"Parcels vs kelp — SpatiallyVarying ({scheme})", rows,
        )
        for metric, _, _, _, ok in rows:
            assert ok, (
                f"{metric}: kelp moment outside tolerance vs Parcels "
                f"({scheme=})"
            )
