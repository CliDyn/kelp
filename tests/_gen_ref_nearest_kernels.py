"""Generate tests/_ref_nearest_kernels.py: verbatim copies of the nearest-node
kernels AND every helper they call, as they were before the node coordinate
table (2026-09-22), renamed with a `_ref_` prefix, so the byte-identity of
that change is pinned against the real old code with no dependency on the
live mesh.py (a later change to a shared helper cannot move both sides of
the parity test).

Base: the tag ``v0.9.0`` — its mesh.py is byte-identical to main @ 96c3d0e,
the branch point (the tag exists in the public export's history, the SHA
does not).

Run once from the repo root:  python tests/_gen_ref_nearest_kernels.py
"""
import ast
import pathlib
import re
import subprocess

BASE = "v0.9.0"
# the six kernels + their transitive callees (all module-level functions) and
# the one module constant the exact search reads
FUNCS = ["_gh_fold_dlon", "_gh_cell_of", "_cap_extents", "_anchor_provable_rect",
         "_gh_scan_cell", "_gh_scan_row_range", "_gh_scan_row_window",
         "_grid_hash_nearest_3x3", "_grid_hash_nearest_widened",
         "_grid_hash_nearest_exact"]
CONSTS = ["_GH_EXACT_SHORT_ROW_CELLS"]
HEADER = '''"""FROZEN copies of the pre-2026-09-22 nearest-node kernels and their helpers
(%s = main @ 96c3d0e, the branch point of feat/node-xyz-nearest).

Generated by tests/_gen_ref_nearest_kernels.py — DO NOT EDIT.  The parity
tests in tests/test_node_xyz.py pin the node-coordinate-table kernels against
these, query by query, ties included.  Nothing here imports from the live
kelp.core.mesh, so a later change to a shared helper cannot move both sides.
"""
import numpy as np
from numba import njit

from kelp.core.geometry import DEG2RAD, RAD2DEG

''' % BASE


def main():
    src = subprocess.run(["git", "show", f"{BASE}:src/kelp/core/mesh.py"],
                         check=True, capture_output=True, text=True).stdout
    tree = ast.parse(src)
    funcs = {}
    consts = {}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in FUNCS:
            funcs[node.name] = ast.get_source_segment(src, node)   # decorator excluded
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 \
                and isinstance(node.targets[0], ast.Name) \
                and node.targets[0].id in CONSTS:
            consts[node.targets[0].id] = ast.get_source_segment(src, node)
    missing = [n for n in FUNCS if n not in funcs] + [c for c in CONSTS if c not in consts]
    assert not missing, missing
    chunks = [consts[c] for c in CONSTS]
    for name in FUNCS:                                            # definition order = FUNCS
        chunks.append("@njit(cache=False)\n" + funcs[name])
    text = "\n\n".join(chunks) + "\n"
    for name in FUNCS + CONSTS:                                   # internal references too
        text = re.sub(rf"\b{name}\b", f"_ref{name}", text)
    out = pathlib.Path(__file__).with_name("_ref_nearest_kernels.py")
    out.write_text(HEADER + text)
    print("wrote", out)


if __name__ == "__main__":
    main()
